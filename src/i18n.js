export function getTranslation(lang = 'vi', key, fallback = '') {
  const current = TRANSLATIONS[lang] || TRANSLATIONS.vi;
  if (current && current[key] !== undefined) return current[key];
  if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined) return TRANSLATIONS.en[key];
  return fallback || key;
}
